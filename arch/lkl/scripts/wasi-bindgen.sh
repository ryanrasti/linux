# The kernel's WASI 0.2 imports (asm/wasi_bindings.h, wasi_bindings.c):
# wit-bindgen's C bindings of the WIT's kernel world (what the drivers
# import), freestanding: the header the kernel's types for libc's, the
# code no cabi_realloc of its own (the module's one allocator is its host
# layer's, which gives the lists the kernel gets: drivers/wasi_libc/, the
# code's libc). Written in the tree, or with --check compared with it:
# fails if they're stale.
#
#   arch/lkl/scripts/wasi-bindgen.sh [--check] <the WIT's directory>
set -eu
check=
if [ "${1:-}" = --check ]; then
	check=1
	shift
fi
wit=$1
tree=$(cd "$(dirname "$0")/../../.." && pwd)
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

if ! wit-bindgen c "$wit" --world kernel --rename-world wasi \
	--no-object-file --out-dir "$tmp" >"$tmp/log" 2>&1; then
	cat "$tmp/log" >&2
	exit 1
fi

# the generated files, each with its banner (trailing spaces trimmed)
out() {
	{
		printf '%s SPDX-License-Identifier: GPL-2.0%s\n' "$1" "$2"
		printf '%s Generated by arch/lkl/scripts/wasi-bindgen.sh: do not edit.%s\n' "$1" "$2"
		cat
	} | sed 's/[[:space:]]*$//' >"$tmp/$3"
}

# (libc's <stdint.h>, <stdbool.h> and <stddef.h>: the kernel's types)
sed -e 's|^#include <stdint.h>$|#include <linux/types.h>|' \
    -e '/^#include <std\(bool\|def\).h>$/d' "$tmp/wasi.h" |
	out '/*' ' */' wasi_bindings.h

# (no cabi_realloc, libc's realloc's: the module's is the host's; and no
# reference to the world's type object: the host layer's bindings have it)
sed -e 's|^#include "wasi.h"$|#include <asm/wasi_bindings.h>|' \
    -e '/^\/\/ Canonical ABI intrinsics$/,/^}$/d' \
    -e '/^\/\/ Ensure that the \*_component_type.o object is linked in$/,$d' \
    "$tmp/wasi.c" | out '//' '' wasi_bindings.c

if grep -n 'realloc(ptr\|__export_name__\|component_type\|#include "' "$tmp"/wasi_bindings.[ch] ||
   grep -n '#include <std' "$tmp"/wasi_bindings.h; then
	echo "$0: wit-bindgen's output isn't as this script knows it" >&2
	exit 1
fi

stale=
for f in include/asm/wasi_bindings.h drivers/wasi_bindings.c; do
	dst=$tree/arch/lkl/$f
	if [ -n "$check" ]; then
		cmp -s "$tmp/${f##*/}" "$dst" || {
			echo "$0: arch/lkl/$f is stale (regenerate it: $0 $wit)" >&2
			stale=1
		}
	else
		cp "$tmp/${f##*/}" "$dst"
	fi
done
[ -z "$stale" ]
